#!/usr/bin/env python3
"""
Generate configuration options parity coverage table for Rocha.
Verifies that every v1 option documented in docs/config.md has >= 1 passing end-to-end test.
"""

import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
CONFIG_MD = os.path.join(PROJECT_ROOT, "docs", "config.md")
COVERAGE_MD = os.path.join(PROJECT_ROOT, "docs", "config-coverage.md")
TESTS_RS = os.path.join(PROJECT_ROOT, "crates", "rocha-cli", "tests", "config_parity_tests.rs")

def main():
    if not os.path.exists(CONFIG_MD):
        print(f"Error: {CONFIG_MD} not found")
        sys.exit(1)

    # 1. Parse v1 options from docs/config.md
    # Table row format:
    # | `option` | Type | Default | CLI Flag | `.mocharc` Key | Mocha Parity | Status | Description |
    v1_options = []
    with open(CONFIG_MD, "r", encoding="utf-8") as f:
        for line in f:
            if line.startswith("| `"):
                raw_parts = re.split(r"(?<!\\)\|", line)[1:-1]
                parts = [p.strip().replace(r"\|", "|") for p in raw_parts]
                if len(parts) >= 8:
                    opt_name = parts[0].replace("`", "")
                    cli_flag = parts[3].replace("`", "")
                    config_key = parts[4].replace("`", "")
                    status = parts[6].replace("`", "")
                    if status == "v1":
                        v1_options.append({
                            "option": opt_name,
                            "cli_flag": cli_flag,
                            "config_key": config_key,
                        })

    print(f"Discovered {len(v1_options)} v1 options from {CONFIG_MD}")

    # 2. Read tests from config_parity_tests.rs
    with open(TESTS_RS, "r", encoding="utf-8") as f:
        tests_src = f.read()

    # 3. Match each option with test
    covered = []
    missing = []

    for item in v1_options:
        opt = item["option"]
        test_fn_name = f"test_config_option_{opt.replace('-', '_')}"
        if f"fn {test_fn_name}(" in tests_src:
            covered.append({
                **item,
                "test": test_fn_name,
                "status": "PASS",
            })
        else:
            missing.append(item)

    print(f"Covered: {len(covered)}/{len(v1_options)}")
    if missing:
        print(f"Missing tests for: {[m['option'] for m in missing]}")

    # 4. Generate coverage markdown
    coverage_pct = (len(covered) / len(v1_options) * 100.0) if v1_options else 0.0

    lines = [
        "# Rocha Configuration Options Parity Coverage",
        "",
        f"**Summary:** {len(covered)} / {len(v1_options)} options verified with passing end-to-end tests ({coverage_pct:.1f}% coverage).",
        "",
        "| Option | Config Key | CLI Flag | Status | Verified Test |",
        "|---|---|---|---|---|",
    ]

    for item in covered:
        lines.append(
            f"| `{item['option']}` | `{item['config_key']}` | `{item['cli_flag']}` | **{item['status']}** | `{item['test']}` |"
        )

    for item in missing:
        lines.append(
            f"| `{item['option']}` | `{item['config_key']}` | `{item['cli_flag']}` | **MISSING** | - |"
        )

    lines.append("")
    lines.append(f"*Auto-generated by `scripts/generate-config-coverage.py`.*")
    lines.append("")

    with open(COVERAGE_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Wrote coverage report to {COVERAGE_MD}")

    if missing:
        sys.exit(1)
    else:
        sys.exit(0)

if __name__ == "__main__":
    main()
